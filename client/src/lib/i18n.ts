const translations: Record<Locale, Record<string, string>> = {
  "en": en,
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  "ja": ja,
  "ko": ko,
  "es": es,
  "pt": pt,
  "ru": ru,
  "ar": ar,
  "vi": vi,
  "th": th,
  "id": id,
};

let currentLocale: Locale = "en";
const listeners: Set<() => void> = new Set();

export function detectLocale(): Locale {
  // Try to detect from saved preference first
  const saved = localStorage.getItem("vera-locale") as Locale | null;
  if (saved && translations[saved]) return saved;
  
  // Try to detect from TG WebApp or browser
  const browserLang = navigator.language || "en";
  const langMap: Record<string, Locale> = {
    "en": "en", "zh": "zh-CN", "zh-CN": "zh-CN", "zh-TW": "zh-TW",
    "ja": "ja", "ko": "ko", "es": "es", "pt": "pt", "ru": "ru",
    "ar": "ar", "vi": "vi", "th": "th", "id": "id",
  };
  return langMap[browserLang] || langMap[browserLang.split("-")[0]] || "en";
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
  localStorage.setItem("vera-locale", locale);
  document.documentElement.lang = locale;
  if (locale === "ar") {
    document.documentElement.dir = "rtl";
  } else {
    document.documentElement.dir = "ltr";
  }
  listeners.forEach(fn => fn());
}

export function getLocale(): Locale {
  return currentLocale;
}

export function t(key: string, params?: Record<string, string | number>): string {
  let text = translations[currentLocale]?.[key] || translations["en"]?.[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

export function useI18n() {
  const [locale, setLocaleState] = useState<Locale>(currentLocale);
  const [, forceUpdate] = useState(0);
  
  const changeLocale = useCallback((newLocale: Locale) => {
    setLocale(newLocale);
    setLocaleState(newLocale);
  }, []);

  // Subscribe to locale changes from other components
  useEffect(() => {
    const listener = () => {
      setLocaleState(currentLocale);
      forceUpdate(n => n + 1);
    };
    listeners.add(listener);
    return () => { listeners.delete(listener); };
  }, []);

  return { locale, t, changeLocale, setLocale: changeLocale, locales: Object.keys(translations) as Locale[] };
}

