/**
 * 根据语言代码获取通知翻译文本
 * @param lang 用户语言代码（如 "zh-CN", "en", "ja" 等）
 * @param key 通知翻译键
 * @param params 插值参数（如 {amount: "100", room: "NL 1/2"}）
 */
export function nt(lang: string | null | undefined, key: NotificationKey, params?: Record<string, string | number>): string {
  // 标准化语言代码
  const normalizedLang = normalizeLang(lang);
  const dict = translations[normalizedLang] || translations["en"];
  let text = dict[key] || translations["en"][key] || key;

  // 替换插值参数
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\$\\{${k}\\}`, "g"), String(v));
    }
  }

  return text;
}

/**
 * 标准化语言代码，映射到支持的语言
 */
function normalizeLang(lang: string | null | undefined): string {
  if (!lang) return "en";
  const lower = lang.toLowerCase();
  
  // 精确匹配
  if (translations[lower]) return lower;
  
  // 映射常见变体
  if (lower.startsWith("zh")) {
    if (lower.includes("tw") || lower.includes("hk") || lower.includes("hant")) return "zh-TW";
    return "zh-CN";
  }
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("ko")) return "ko";
  if (lower.startsWith("es")) return "es";
  if (lower.startsWith("pt")) return "pt";
  if (lower.startsWith("ru")) return "ru";
  if (lower.startsWith("ar")) return "ar";
  if (lower.startsWith("vi")) return "vi";
  if (lower.startsWith("th")) return "th";
  if (lower.startsWith("id") || lower.startsWith("ms")) return "id";
  
  return "en";
}

/**
 * 获取用户语言代码（从数据库查询）
 */
export async function getUserLang(userId: number): Promise<string> {
  try {
    const { getDb } = await import("./db");
    const { users } = await import("../drizzle/schema");
    const { eq } = await import("drizzle-orm");
    const db = await getDb();
    if (!db) return "en";
    const [user] = await db.select({ language: users.language }).from(users).where(eq(users.id, userId)).limit(1);
    return user?.language || "en";
  } catch {
    return "en";
  }
}
