// For each locale, find the closing brace of its const and insert missing keys before it
for (const [localeVar, missingTranslations] of Object.entries(translations)) {
  const keys = Object.entries(missingTranslations);
  if (keys.length === 0) continue;
  
  // Find the end of this locale's object (the closing `};` line)
  const startRegex = new RegExp(`^const ${localeVar}: Record<string, string> = \\{`, 'm');
  const startMatch = content.match(startRegex);
  if (!startMatch) {
    console.error(`Could not find locale var: ${localeVar}`);
    continue;
  }
  
  const startIndex = startMatch.index + startMatch[0].length;
  let braceCount = 1;
  let i = startIndex;
  while (i < content.length && braceCount > 0) {
    if (content[i] === '{') braceCount++;
    if (content[i] === '}') braceCount--;
    i++;
  }
  
  // i is now just past the closing brace
  // Insert before the closing brace
  const insertPoint = i - 1;
  
  // Build the new entries
  const newEntries = keys.map(([key, value]) => {
    const escaped = value.replace(/"/g, '\\"');
    return `  "${key}": "${escaped}",`;
  }).join('\n');
  
  const insertion = '\n  // Auto-generated missing translations\n' + newEntries + '\n';
  
  content = content.substring(0, insertPoint) + insertion + content.substring(insertPoint);
  
  console.log(`✅ Added ${keys.length} keys to ${localeVar}`);
}

writeFileSync(i18nPath, content, 'utf-8');
